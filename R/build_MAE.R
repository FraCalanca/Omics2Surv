#' Build a MultiAssayExperiment Object from SummarizedExperiment Objects
#'
#' Constructs a \code{MultiAssayExperiment} (MAE) container integrating multiple
#' omics \code{SummarizedExperiment} objects with associated clinical data.
#' Supports the case where different omics assays cover different subsets of
#' samples, as is typical after per-omic train/test splitting and preprocessing.
#'
#' @param omics_list Named list of \code{SummarizedExperiment} objects, one per
#'   omics layer (e.g. \code{list(mRNA = se_rna, miRNA = se_mirna, CNV = se_cnv,
#'   methylation = se_meth)}). List names become experiment identifiers in the
#'   MAE. Column names of each SE must be set to sample identifiers.
#' @param clinical_data Matrix or data frame of clinical data with \strong{variables
#'   as rows} and \strong{samples as columns} (the same orientation used by the
#'   \code{prepare_*} functions). Must contain at least the union of all sample
#'   identifiers present across \code{omics_list}. Rows \code{"overall_survival"}
#'   and \code{"status"} are expected for survival analysis.
#'
#' @return A \code{MultiAssayExperiment} object with:
#'   \itemize{
#'     \item \code{experiments}: The assays from \code{omics_list}.
#'     \item \code{colData}: Clinical data as a \code{DataFrame} (samples as rows,
#'       variables as columns).
#'     \item \code{sampleMap}: Auto-generated by \code{MultiAssayExperiment},
#'       mapping each assay column to its \code{colData} row.
#'   }
#'
#' @details
#' \strong{Common sample assumption:} multi-omics survival analysis requires
#' the same patients across all layers. When \code{omics_list} contains more
#' than one element, \code{build_MAE} automatically restricts all assays to
#' their common sample set (intersection). A message reports how many samples
#' are dropped per assay. If the intersection is empty the function stops with
#' an error.
#'
#'
#' @seealso \code{\link[MultiAssayExperiment]{MultiAssayExperiment}},
#'   \code{\link{prepare_RNA}}, \code{\link{prepare_methyl}},
#'   \code{\link{prepare_CNV}}
#'
#' @export
build_MAE <- function(omics_list, clinical_data) {

  # ── Validate inputs ──────────────────────────────────────────────
  if (!is.list(omics_list) || is.null(names(omics_list))) {
    stop("'omics_list' must be a named list.")
  }

  not_se <- !sapply(omics_list, inherits, "SummarizedExperiment")
  if (any(not_se)) {
    stop(
      "All elements of 'omics_list' must be SummarizedExperiment objects. ",
      "Non-conforming: ", paste(names(omics_list)[not_se], collapse = ", ")
    )
  }

  # ── Intersect samples (multi-omics assumption) ───────────────────
  if (length(omics_list) > 1L) {

    common_samples <- Reduce(intersect, lapply(omics_list, colnames))

    if (length(common_samples) == 0L) {
      stop("No common samples found across all assays in omics_list.")
    }

    n_before   <- sapply(omics_list, ncol)
    omics_list <- lapply(omics_list, function(se) se[, common_samples, drop = FALSE])

    dropped <- n_before - length(common_samples)
    message("Samples filtered to common set: ", length(common_samples),
            " samples retained.")
    for (nm in names(dropped)[dropped > 0L]) {
      message("  '", nm, "': ", dropped[nm], " sample(s) dropped.")
    }

    all_samples <- common_samples

  } else {
    all_samples <- colnames(omics_list[[1L]])
    message("Single assay: ", length(all_samples), " samples.")
  }

  # ── Check clinical_data covers all samples ───────────────────────
  missing_samples <- setdiff(all_samples, colnames(clinical_data))
  if (length(missing_samples) > 0L) {
    stop(
      length(missing_samples), " sample(s) not found in clinical_data: ",
      paste(head(missing_samples, 10L), collapse = ", "),
      if (length(missing_samples) > 10L) " ..." else ""
    )
  }

  # ── Build colData ────────────────────────────────────────────────
  # clinical_data: variables x samples → transpose to samples x variables
  col_data <- as.data.frame(
    t(clinical_data[, all_samples, drop = FALSE])
  )
  # preserve rownames through type.convert
  sample_ids       <- rownames(col_data)
  col_data         <- as.data.frame(lapply(col_data, type.convert, as.is = FALSE))
  rownames(col_data) <- sample_ids

  # ── Build explicit sampleMap ─────────────────────────────────────
  sample_map_list <- lapply(names(omics_list), function(nm) {
    samples <- colnames(omics_list[[nm]])
    data.frame(
      assay   = nm,
      primary = samples,
      colname = samples,
      stringsAsFactors = FALSE
    )
  })
  sample_map <- S4Vectors::DataFrame(do.call(rbind, sample_map_list))

  # ── Build MAE ────────────────────────────────────────────────────
  mae <- MultiAssayExperiment::MultiAssayExperiment(
    experiments = omics_list,
    colData     = S4Vectors::DataFrame(col_data),
    sampleMap   = sample_map
  )

  message(
    "MultiAssayExperiment built with ", length(omics_list), " assay(s): ",
    paste(names(omics_list), collapse = ", "), ".\n",
    "Samples in colData: ", nrow(col_data), "."
  )

  return(mae)
}
